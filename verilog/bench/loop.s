# 命令キャッシュの効果を見るためのループ (Verilog 版で追加)
#   表 D0 の 8 語を 100 回なめて合計し, 各回 1 語を書き換える。
#   最後に合計を期待値と比べ, 合っていれば SUCCESS (0x3F0) で止まる。
#
# Header start
#
USING   14,300
USING_I 14,300
EQU 300
main:
X   0,0,0
O   14,0,%300
B   L1
#
EQU 3D0
DEAD:
DD000000
EQU 3F0
SUCCESS:
DF000000
#
# Header end
##########################################
EQU 400
# GR1 = 回数, GR4 = 回数の上限, GR2 = 合計, GR8 = 表の番地
L1:
O   1,0,%0
O   4,0,%64
O   2,0,%0
O   8,0,%700
LOOP:
L   3,8(0)
A   2,2,3
L   3,8(4)
A   2,2,3
L   3,8(8)
A   2,2,3
L   3,8(C)
A   2,2,3
L   3,8(10)
A   2,2,3
L   3,8(14)
A   2,2,3
L   3,8(18)
A   2,2,3
L   3,8(1C)
A   2,2,3
# 表の先頭を 1 増やす (ストアの直後のロードはフォワーディングで読む)
L   3,8(0)
A   3,3,%1
ST  3,8(0)
A   1,1,%1
C   1,4
BL  LOOP
# 合計 = 100 * 36 + (0 + 1 + ... + 99) = 3600 + 4950 = 8550 = 0x2166
O   5,0,%2166
C   2,5
BNE DEAD
B   SUCCESS
#
EQU 700
D0:
00000001
00000002
00000003
00000004
00000005
00000006
00000007
00000008
