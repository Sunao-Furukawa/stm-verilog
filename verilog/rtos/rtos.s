# STM-RTOS : STM-1.2 用の小さなリアルタイム OS (Verilog 版で追加)
#
#   python tools/asm.py rtos/rtos.s 20000 -o mem.dat   でアセンブルする。
#   詳しくは rtos/README.ja.md を参照。
#
#   * 4 タスク, 固定優先度 (数字が小さいほど高い) のプリエンプティブ・スケジューリング。
#     同じ優先度のタスクは YIELD で順番に回る。
#   * タスクはユーザモードで動き, システムコールは SVC n (未定義命令 E00000nn) で呼ぶ。
#     違法命令例外でカーネルに入り, XPC の命令語から n を取り出す。
#   * 計数セマフォ 4 個, メールボックス 2 個 (各 4 通まで)。
#   * タスクが例外 (オーバフロー, 違法命令, コンペアストップ, バスエラー) を起こしたら
#     そのタスクだけを終了させる。
#   * STM にはタイマ割り込みが無いので, タスクの切り替えはシステムコールの時だけ起きる。
#
# システムコール (引数 GR1, GR2 / 戻り値 GR1, 他の GR は保存される)
#   SVC 0  EXIT                       タスクを終了
#   SVC 1  YIELD                      同じ優先度の次のタスクに譲る
#   SVC 2  SEM_WAIT  (GR1=sem)        -> 0 / -1 (ID 不正)
#   SVC 3  SEM_SIGNAL(GR1=sem)        -> 0 / -1
#   SVC 4  SEND (GR1=mbx, GR2=msg)    -> 0 / -1 (ID 不正, 満杯)
#   SVC 5  RECV (GR1=mbx)             -> msg / -1
#   SVC 6  LOG  (GR1=値)              ログ領域 (E00) に 1 語追加
#   SVC 7  GETTID                     -> タスク番号 (0〜3)
#
# メモリマップ (4KB)
#   300        リセット (main)            3D0 DEAD   3E0 DEADLOCK   3F0 SUCCESS
#   400-41F    システムコールの分岐表      440- トラップ入口とカーネル
#   900-AFF    ユーザタスク (T0 900, T1 980, T2 A00, T3 A80)
#   B00-       全タスク終了後の結果検査 (アプリケーション側)
#   C00-D7F    TCB x 4 (各 60)
#   D80        CURIDX (実行中のタスク番号)   D84 LOGCNT (ログの語数)
#   D90-D9F    セマフォ x 4 (計数値)
#   DA0-DDF    メールボックス x 2 (各 20: +0 通数, +4 読み位置, +8 書き位置, +10 4 通分)
#   E00-E7F    ログ (32 語)
#   F00-F1F    タスク表 (入口番地, 優先度) x 4
#   F40-       ログの期待値 (F40 = 語数, F44- = 値)
#
# TCB (60 バイト)
#   +00-3C GR0-GR15   +40 PC   +44 PSW   +48 状態 (0=休止, 1=実行可能, 2=待ち)
#   +4C 優先度        +50 待っているオブジェクトの番地   +54 タスク番号
#
# カーネル内のレジスタ: GR0 = 0, GR14 = 0 (ラベルの番地を絶対番地で使う),
#                       GR13 = 実行中の TCB, GR15 = サブルーチンの戻り番地
#
# ハードウェアの不具合への対策 (rtos/README.ja.md 参照。rtos/check_bc.py で検査する)
#   (1) 条件分岐の予測ミスで取り消した命令の結果が, 正しい側の最初の命令組に
#       バイパスされる。そこで
#         * エラーなどへの分岐は前方分岐にする (前方分岐は not taken と予測される)
#         * 分岐先の最初の 2 命令は, 反対側の最初の 4 命令が書くレジスタを読まない
#   (2) WSR の GR, ストアのベースレジスタは, 直前のロードの結果を待たない。
#       ロードしたら EX 命令でコピーしてから使う。
#
# アセンブラについての注意: 命令は行頭から書く。ラベルは 1 行に 1 つ。
#   データ行の後で分岐命令を書くときは, 間に EQU を置く。
#
USING   14,0
USING_I 14,0
EQU 300
main:
X   0,0,0
X   14,14,14
B   KBOOT
#
EQU 3D0
DEAD:
DD000000
EQU 3E0
DEADLOCK:
DE000000
EQU 3F0
SUCCESS:
DF000000
#
##########################################################################
# システムコールの分岐表 (SVC n -> 400 + 4n)
##########################################################################
EQU 400
SVCTBL:
B   K_EXIT
B   K_YIELD
B   K_SEMWAIT
B   K_SEMSIG
B   K_SEND
B   K_RECV
B   K_LOG
B   K_GETTID
#
##########################################################################
# トラップ入口 (TBR = 440)
#   実行中のタスクの GR0-15, PC (= XPC), PSW (= XPSW) を TCB に保存する。
#   SVR0 (SR8) は常に実行中の TCB の番地を持つ。
##########################################################################
EQU 440
TRAP:
WSR 9,15
RSR 15,8
ST  0,15(0)
ST  1,15(4)
ST  2,15(8)
ST  3,15(C)
ST  4,15(10)
ST  5,15(14)
ST  6,15(18)
ST  7,15(1C)
ST  8,15(20)
ST  9,15(24)
ST  10,15(28)
ST  11,15(2C)
ST  12,15(30)
ST  13,15(34)
ST  14,15(38)
RSR 0,9
ST  0,15(3C)
RSR 0,5
ST  0,15(40)
RSR 0,4
ST  0,15(44)
X   0,0,0
X   14,14,14
O   13,15,%0
# 割り込みの種類 = PSW の INTTYPE (ビット 8-15)
RSR 1,0
SRL 1,1,%10
N   1,1,%FF
C   1,%1
BNE K_FAULT
# 違法命令: SVC (E00000nn) ならシステムコール
L   2,13(40)
L   3,2(0)
SRL 4,3,%18
C   4,%E0
BNE K_FAULT
A   2,2,%4
ST  2,13(40)
N   4,3,%FF
C   4,%8
BGE K_ERR
SL  4,4,%2
J   4(400)
#
# SVC 1 YIELD : 次の番号のタスクから探す (同じ優先度なら次のタスクが選ばれる)
K_YIELD:
L   11,CURIDX
A   11,11,%1
N   11,11,%3
B   SCHED
#
# SVC 6 LOG
K_LOG:
L   1,13(4)
BAL 15,K_LOGPUT
B   K_RESUME
#
# SVC 7 GETTID
K_GETTID:
L   1,CURIDX
B   K_RET
#
# SVC 2 SEM_WAIT
K_SEMWAIT:
L   1,13(4)
CU  1,%4
BGE K_ERR
SL  1,1,%2
A   1,1,%D90
L   2,1(0)
C   2,%0
BLE KSW_BLOCK
A   2,2,%-1
ST  2,1(0)
X   1,1,1
B   K_RET
KSW_BLOCK:
X   2,2,2
ST  2,13(4)
B   K_BLOCK
#
# SVC 3 SEM_SIGNAL
K_SEMSIG:
L   1,13(4)
CU  1,%4
BGE K_ERR
SL  1,1,%2
A   1,1,%D90
BAL 15,K_WAKE1
C   2,%0
BGE K_WOKEN
L   2,1(0)
A   2,2,%1
ST  2,1(0)
X   1,1,1
B   K_RET
#
# 待ちのタスクを起こした: 戻り値 0 を返し, 優先度の高い方を実行する
# (同じ優先度なら実行中のタスクが続ける)
K_WOKEN:
X   1,1,1
ST  1,13(4)
L   11,CURIDX
B   SCHED
#
# SVC 4 SEND : 受信待ちのタスクがいれば直接渡す, いなければ箱に入れる
K_SEND:
L   1,13(4)
CU  1,%2
BGE K_ERR
SL  1,1,%5
A   1,1,%DA0
BAL 15,K_WAKE1
C   2,%0
BGE KSD_HAND
L   5,1(0)
C   5,%4
BGE K_ERR
A   5,5,%1
ST  5,1(0)
L   6,1(8)
SL  7,6,%2
A   7,7,1
L   5,13(8)
ST  5,7(10)
A   6,6,%1
N   6,6,%3
ST  6,1(8)
X   1,1,1
B   K_RET
# 受信待ちのタスク (TCB = GR2) の GR1 にメッセージを入れる
KSD_HAND:
L   3,13(8)
ST  3,2(4)
B   K_WOKEN
#
# SVC 5 RECV : 箱が空なら待つ (メッセージは SEND 側が GR1 に入れる)
K_RECV:
L   1,13(4)
CU  1,%2
BGE K_ERR
SL  1,1,%5
A   1,1,%DA0
L   2,1(0)
C   2,%0
BLE K_BLOCK
A   2,2,%-1
ST  2,1(0)
L   3,1(4)
SL  4,3,%2
A   4,4,1
L   5,4(10)
A   3,3,%1
N   3,3,%3
ST  3,1(4)
O   1,5,%0
B   K_RET
#
# 実行中のタスクを, GR1 のオブジェクトの待ちにして切り替える
K_BLOCK:
ST  1,13(50)
O   2,0,%2
ST  2,13(48)
L   11,CURIDX
B   SCHED
#
# 戻り値 -1 で戻る
K_ERR:
O   1,0,%-1
#
# 戻り値 GR1 で実行中のタスクに戻る
K_RET:
ST  1,13(4)
#
# 実行中のタスクにそのまま戻る
K_RESUME:
O   8,13,%0
B   DISPATCH
#
# タスクの例外: ログに E0+INTTYPE を残してタスクを終了する
K_FAULT:
A   1,1,%E0
BAL 15,K_LOGPUT
#
# SVC 0 EXIT
K_EXIT:
X   1,1,1
ST  1,13(48)
L   11,CURIDX
B   SCHED
#
##########################################################################
# スケジューラ
#   入力 GR11 = 探し始めるタスク番号。そこから順に 4 個の TCB を見て,
#   実行可能で優先度が最も高い (同じなら先に見つけた) タスクを選ぶ。
##########################################################################
SCHED:
O   9,0,%7FFF
O   8,0,%-1
O   7,0,%0
SC_LOOP:
SL  1,11,%6
SL  2,11,%5
A   1,1,2
A   1,1,%C00
L   3,1(48)
C   3,%1
BNE SC_NEXT
L   3,1(4C)
C   3,9
BL  SC_BETTER
SC_NEXT:
A   11,11,%1
N   11,11,%3
A   7,7,%1
C   7,%4
BL  SC_LOOP
C   8,%0
BGE DISPATCH
# 実行できるタスクが無い: 待ちのタスクが残っていればデッドロック,
# 全タスクが終わっていればアプリケーションの終了処理へ
O   1,0,%C00
O   7,0,%0
SC_IDLE:
L   3,1(48)
C   3,%2
BE  DEADLOCK
A   1,1,%60
A   7,7,%1
C   7,%4
BL  SC_IDLE
B   APP_DONE
# これまでで最も優先度が高い: 優先度 GR9 と TCB GR8 を更新
SC_BETTER:
O   9,3,%0
O   8,1,%0
B   SC_NEXT
#
##########################################################################
# ディスパッチ: TCB (GR8) のタスクを復帰して RFE で実行する
##########################################################################
DISPATCH:
O   15,8,%0
L   9,15(54)
ST  9,CURIDX
WSR 8,15
L   1,15(40)
O   1,1,%0
WSR 5,1
L   1,15(44)
O   1,1,%0
WSR 4,1
L   0,15(0)
L   1,15(4)
L   2,15(8)
L   3,15(C)
L   4,15(10)
L   5,15(14)
L   6,15(18)
L   7,15(1C)
L   8,15(20)
L   9,15(24)
L   10,15(28)
L   11,15(2C)
L   12,15(30)
L   13,15(34)
L   14,15(38)
L   15,15(3C)
RFE
#
##########################################################################
# サブルーチン (BAL 15,xxx で呼ぶ)
##########################################################################
# K_LOGPUT: GR1 をログに追加する (満杯なら捨てる)。GR2, GR3 を壊す
K_LOGPUT:
L   2,LOGCNT
C   2,%20
BGE KLP_RET
SL  3,2,%2
ST  1,3(E00)
A   2,2,%1
ST  2,LOGCNT
KLP_RET:
J   15(0)
#
# K_WAKE1: GR1 のオブジェクトを待っているタスクのうち, 優先度が最も高い
#   (同じなら番号の小さい) タスクを実行可能にする。
#   GR2 = その TCB の番地, いなければ -1。GR3-GR7 を壊す
K_WAKE1:
O   2,0,%-1
O   7,0,%7FFF
O   3,0,%C00
O   4,0,%0
KW_LOOP:
O   6,3,%0
L   5,3(48)
C   5,%2
BNE KW_NEXT
L   5,3(50)
C   5,1
BNE KW_NEXT
L   5,3(4C)
C   5,7
BL  KW_BETTER
KW_NEXT:
A   3,3,%60
A   4,4,%1
C   4,%4
BL  KW_LOOP
C   2,%0
BL  KW_RET
O   5,0,%1
ST  5,2(48)
X   5,5,5
ST  5,2(50)
KW_RET:
J   15(0)
KW_BETTER:
O   7,5,%0
O   2,6,%0
B   KW_NEXT
#
##########################################################################
# 起動: カーネル変数を 0 にし, タスク表から TCB を作ってタスク 0 から始める
##########################################################################
KBOOT:
O   1,0,%440
WSR 2,1
O   2,0,%D80
KB_ZERO:
ST  0,2(0)
A   2,2,%4
C   2,%E80
BL  KB_ZERO
O   13,0,%C00
O   12,0,%F00
O   11,0,%0
SETHI 10,%0100
KB_TASK:
O   2,0,%0
KB_CLR:
A   3,13,2
ST  0,3(0)
A   2,2,%4
C   2,%40
BL  KB_CLR
ST  11,13(4)
ST  11,13(54)
L   1,12(0)
ST  1,13(40)
ST  10,13(44)
O   1,0,%1
ST  1,13(48)
L   1,12(4)
ST  1,13(4C)
ST  0,13(50)
A   13,13,%60
A   12,12,%8
A   11,11,%1
C   11,%4
BL  KB_TASK
O   11,0,%0
B   SCHED
#
##########################################################################
# ユーザタスク (ユーザモード, 開始時 GR1 = タスク番号, 他の GR = 0)
##########################################################################
# T0 (優先度 1): メールボックス 0 から 3 通受け取ってログに残し, セマフォ 0 を上げる
EQU 900
TASK0:
O   10,0,%1234
O   1,0,%A0
SVC 6
O   3,0,%3
T0_LOOP:
X   1,1,1
SVC 5
SVC 6
A   3,3,%-1
C   3,%0
BG  T0_LOOP
X   1,1,1
SVC 3
C   10,%1234
BE  T0_END
O   1,0,%BAD
SVC 6
T0_END:
SVC 0
#
# T1 (優先度 2): 11, 22, 33 を送る (送るたびに T0 に切り替わる)。
#   その後 44, 55 を送る (受け手がいないので箱にたまる)
EQU 980
TASK1:
O   10,0,%5678
O   1,0,%B0
SVC 6
O   4,0,%0
T1_LOOP:
A   4,4,%11
X   1,1,1
O   2,4,%0
SVC 4
SRL 1,4,%4
A   1,1,%B0
SVC 6
C   4,%33
BL  T1_LOOP
X   1,1,1
O   2,0,%44
SVC 4
X   1,1,1
O   2,0,%55
SVC 4
O   1,0,%B4
SVC 6
C   10,%5678
BE  T1_END
O   1,0,%BAD
SVC 6
T1_END:
SVC 0
#
# T2 (優先度 3): T3 と交互に動く。最後にわざとオーバフローを起こして終了させられる
EQU A00
TASK2:
O   1,0,%C0
SVC 6
SVC 1
O   1,0,%C1
SVC 6
X   1,1,1
SVC 2
O   1,0,%C2
SVC 6
O   1,0,%1
SVC 3
O   1,0,%C3
SVC 6
SVC 1
O   1,0,%C4
SVC 6
SETHI 1,%7FFF
A   1,1,1
O   1,0,%C5
SVC 6
SVC 0
#
# T3 (優先度 3): セマフォ 1 を待ち, 箱にたまった 2 通を受け取る。
#   最後に不正な ID でエラー (-1) が返ることを確かめる
EQU A80
TASK3:
O   1,0,%D0
SVC 6
O   1,0,%1
SVC 2
O   1,0,%D1
SVC 6
X   1,1,1
SVC 5
SVC 6
X   1,1,1
SVC 5
SVC 6
O   1,0,%9
SVC 2
C   1,%-1
BE  T3_END
O   1,0,%BAD
SVC 6
T3_END:
SVC 0
#
##########################################################################
# 全タスク終了後 (カーネルモード): ログを期待値と比べる
##########################################################################
EQU B00
APP_DONE:
L   1,LOGCNT
L   2,EXPCNT
C   1,2
BNE DEAD
O   3,0,%0
O   4,0,%0
AD_LOOP:
C   4,2
BGE SUCCESS
L   5,3(E00)
L   6,3(F44)
C   5,6
BNE DEAD
A   3,3,%4
A   4,4,%1
B   AD_LOOP
#
