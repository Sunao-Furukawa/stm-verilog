# STM-RTOS のアプリケーション: スイッチで選んだあいさつを UART に出す (Arty A7-35 用)
#
#   カーネル (main〜KBOOT) は rtos/rtos.s と同じもの。ユーザタスクとデータだけが違う。
#   verilog/syn/vivado/create_bd.tcl のブロックデザイン (UART Lite + スイッチ用 GPIO) で動く。
#
#   SW1 SW0   出力
#    0   0    Hello
#    0   1    Nihao
#    1   0    Konnichiwa
#    1   1    annyeonghaseyo
#   (SW2, SW3 は使わない)
#
#   約 0.5 秒ごとに 1 行 (CR LF 付き, 115200 baud) を出す。スイッチを切り替えると,
#   次の行から出力が変わる。
#
#   タスク
#     T0 (優先度 1) 出力タスク: メールボックス 0 から文字列の番地を受け取り (RECV), UART に出す。
#                   出し終わると次の RECV で待ちに入る。
#     T1 (優先度 2) スイッチのタスク: スイッチを読み, 対応する文字列の番地を
#                   メールボックス 0 に送る (SEND)。受信待ちの T0 の方が優先度が高いので,
#                   SEND の時点で T0 に切り替わり, 1 行出し終わってから T1 に戻る。
#                   その後, 空ループで約 0.5 秒待って繰り返す。
#     T2, T3        使わない (すぐ EXIT)
#   STM にはタイマ割り込みが無いので, 待ち時間は T1 の空ループで作る (回数は DELAY)。
#
#   入出力 (CPU の I/O 領域。ユーザモードのタスクからそのまま読み書きする)
#     F000_0000  AXI UART Lite   +4 送信 FIFO, +8 ステータス (ビット 3 = 送信 FIFO が満杯)
#     F001_0000  AXI GPIO        +0 データ (ビット 0〜3 = SW0〜SW3)
#
#   verilog フォルダで:
#     python tools/asm.py rtos/greet_uart.s 20000 -o work/greet_uart.dat
#     python tools/mem2hex.py work/greet_uart.dat work/greet_uart.hex
#   できた .hex を create_bd.tcl の 2 番目の引数に渡す。
#
# メモリマップ (4KB) は rtos/rtos.s と同じ。違うところ:
#   900 T0, 980 T1, A00 T2/T3 (EXIT)
#   B00        全タスクが終わった場合 (起きないはず): DEAD で止まる
#   B80-BFF    文字列 (各 20 バイト)
#   F00-F1F    タスク表        F20-F2F 文字列の番地の表      F30 DELAY (待ちの空ループ回数)
#
# ハードウェアの不具合への対策は rtos/rtos.s と同じ (rtos/check_bc.py で検査する)。
#
USING   14,0
USING_I 14,0
EQU 300
main:
X   0,0,0
X   14,14,14
B   KBOOT
#
EQU 3D0
DEAD:
DD000000
EQU 3E0
DEADLOCK:
DE000000
EQU 3F0
SUCCESS:
DF000000
#
##########################################################################
# システムコールの分岐表 (SVC n -> 400 + 4n)
##########################################################################
EQU 400
SVCTBL:
B   K_EXIT
B   K_YIELD
B   K_SEMWAIT
B   K_SEMSIG
B   K_SEND
B   K_RECV
B   K_LOG
B   K_GETTID
#
##########################################################################
# トラップ入口 (TBR = 440)
#   実行中のタスクの GR0-15, PC (= XPC), PSW (= XPSW) を TCB に保存する。
#   SVR0 (SR8) は常に実行中の TCB の番地を持つ。
##########################################################################
EQU 440
TRAP:
WSR 9,15
RSR 15,8
ST  0,15(0)
ST  1,15(4)
ST  2,15(8)
ST  3,15(C)
ST  4,15(10)
ST  5,15(14)
ST  6,15(18)
ST  7,15(1C)
ST  8,15(20)
ST  9,15(24)
ST  10,15(28)
ST  11,15(2C)
ST  12,15(30)
ST  13,15(34)
ST  14,15(38)
RSR 0,9
ST  0,15(3C)
RSR 0,5
ST  0,15(40)
RSR 0,4
ST  0,15(44)
X   0,0,0
X   14,14,14
O   13,15,%0
# 割り込みの種類 = PSW の INTTYPE (ビット 8-15)
RSR 1,0
SRL 1,1,%10
N   1,1,%FF
C   1,%1
BNE K_FAULT
# 違法命令: SVC (E00000nn) ならシステムコール
L   2,13(40)
L   3,2(0)
SRL 4,3,%18
C   4,%E0
BNE K_FAULT
A   2,2,%4
ST  2,13(40)
N   4,3,%FF
C   4,%8
BGE K_ERR
SL  4,4,%2
J   4(400)
#
# SVC 1 YIELD : 次の番号のタスクから探す (同じ優先度なら次のタスクが選ばれる)
K_YIELD:
L   11,CURIDX
A   11,11,%1
N   11,11,%3
B   SCHED
#
# SVC 6 LOG
K_LOG:
L   1,13(4)
BAL 15,K_LOGPUT
B   K_RESUME
#
# SVC 7 GETTID
K_GETTID:
L   1,CURIDX
B   K_RET
#
# SVC 2 SEM_WAIT
K_SEMWAIT:
L   1,13(4)
CU  1,%4
BGE K_ERR
SL  1,1,%2
A   1,1,%D90
L   2,1(0)
C   2,%0
BLE KSW_BLOCK
A   2,2,%-1
ST  2,1(0)
X   1,1,1
B   K_RET
KSW_BLOCK:
X   2,2,2
ST  2,13(4)
B   K_BLOCK
#
# SVC 3 SEM_SIGNAL
K_SEMSIG:
L   1,13(4)
CU  1,%4
BGE K_ERR
SL  1,1,%2
A   1,1,%D90
BAL 15,K_WAKE1
C   2,%0
BGE K_WOKEN
L   2,1(0)
A   2,2,%1
ST  2,1(0)
X   1,1,1
B   K_RET
#
# 待ちのタスクを起こした: 戻り値 0 を返し, 優先度の高い方を実行する
# (同じ優先度なら実行中のタスクが続ける)
K_WOKEN:
X   1,1,1
ST  1,13(4)
L   11,CURIDX
B   SCHED
#
# SVC 4 SEND : 受信待ちのタスクがいれば直接渡す, いなければ箱に入れる
K_SEND:
L   1,13(4)
CU  1,%2
BGE K_ERR
SL  1,1,%5
A   1,1,%DA0
BAL 15,K_WAKE1
C   2,%0
BGE KSD_HAND
L   5,1(0)
C   5,%4
BGE K_ERR
A   5,5,%1
ST  5,1(0)
L   6,1(8)
SL  7,6,%2
A   7,7,1
L   5,13(8)
ST  5,7(10)
A   6,6,%1
N   6,6,%3
ST  6,1(8)
X   1,1,1
B   K_RET
# 受信待ちのタスク (TCB = GR2) の GR1 にメッセージを入れる
KSD_HAND:
L   3,13(8)
ST  3,2(4)
B   K_WOKEN
#
# SVC 5 RECV : 箱が空なら待つ (メッセージは SEND 側が GR1 に入れる)
K_RECV:
L   1,13(4)
CU  1,%2
BGE K_ERR
SL  1,1,%5
A   1,1,%DA0
L   2,1(0)
C   2,%0
BLE K_BLOCK
A   2,2,%-1
ST  2,1(0)
L   3,1(4)
SL  4,3,%2
A   4,4,1
L   5,4(10)
A   3,3,%1
N   3,3,%3
ST  3,1(4)
O   1,5,%0
B   K_RET
#
# 実行中のタスクを, GR1 のオブジェクトの待ちにして切り替える
K_BLOCK:
ST  1,13(50)
O   2,0,%2
ST  2,13(48)
L   11,CURIDX
B   SCHED
#
# 戻り値 -1 で戻る
K_ERR:
O   1,0,%-1
#
# 戻り値 GR1 で実行中のタスクに戻る
K_RET:
ST  1,13(4)
#
# 実行中のタスクにそのまま戻る
K_RESUME:
O   8,13,%0
B   DISPATCH
#
# タスクの例外: ログに E0+INTTYPE を残してタスクを終了する
K_FAULT:
A   1,1,%E0
BAL 15,K_LOGPUT
#
# SVC 0 EXIT
K_EXIT:
X   1,1,1
ST  1,13(48)
L   11,CURIDX
B   SCHED
#
##########################################################################
# スケジューラ
#   入力 GR11 = 探し始めるタスク番号。そこから順に 4 個の TCB を見て,
#   実行可能で優先度が最も高い (同じなら先に見つけた) タスクを選ぶ。
##########################################################################
SCHED:
O   9,0,%7FFF
O   8,0,%-1
O   7,0,%0
SC_LOOP:
SL  1,11,%6
SL  2,11,%5
A   1,1,2
A   1,1,%C00
L   3,1(48)
C   3,%1
BNE SC_NEXT
L   3,1(4C)
C   3,9
BL  SC_BETTER
SC_NEXT:
A   11,11,%1
N   11,11,%3
A   7,7,%1
C   7,%4
BL  SC_LOOP
C   8,%0
BGE DISPATCH
# 実行できるタスクが無い: 待ちのタスクが残っていればデッドロック,
# 全タスクが終わっていればアプリケーションの終了処理へ
O   1,0,%C00
O   7,0,%0
SC_IDLE:
L   3,1(48)
C   3,%2
BE  DEADLOCK
A   1,1,%60
A   7,7,%1
C   7,%4
BL  SC_IDLE
B   APP_DONE
# これまでで最も優先度が高い: 優先度 GR9 と TCB GR8 を更新
SC_BETTER:
O   9,3,%0
O   8,1,%0
B   SC_NEXT
#
##########################################################################
# ディスパッチ: TCB (GR8) のタスクを復帰して RFE で実行する
##########################################################################
DISPATCH:
O   15,8,%0
L   9,15(54)
ST  9,CURIDX
WSR 8,15
L   1,15(40)
O   1,1,%0
WSR 5,1
L   1,15(44)
O   1,1,%0
WSR 4,1
L   0,15(0)
L   1,15(4)
L   2,15(8)
L   3,15(C)
L   4,15(10)
L   5,15(14)
L   6,15(18)
L   7,15(1C)
L   8,15(20)
L   9,15(24)
L   10,15(28)
L   11,15(2C)
L   12,15(30)
L   13,15(34)
L   14,15(38)
L   15,15(3C)
RFE
# ここには来ない。RFE の後ろで条件分岐を先に発行させないためのもの (不具合 3)
DSP_SPIN:
B   DSP_SPIN
#
##########################################################################
# サブルーチン (BAL 15,xxx で呼ぶ)
##########################################################################
# K_LOGPUT: GR1 をログに追加する (満杯なら捨てる)。GR2, GR3 を壊す
K_LOGPUT:
L   2,LOGCNT
C   2,%20
BGE KLP_RET
SL  3,2,%2
ST  1,3(E00)
A   2,2,%1
ST  2,LOGCNT
KLP_RET:
J   15(0)
#
# K_WAKE1: GR1 のオブジェクトを待っているタスクのうち, 優先度が最も高い
#   (同じなら番号の小さい) タスクを実行可能にする。
#   GR2 = その TCB の番地, いなければ -1。GR3-GR7 を壊す
K_WAKE1:
O   2,0,%-1
O   7,0,%7FFF
O   3,0,%C00
O   4,0,%0
KW_LOOP:
O   6,3,%0
L   5,3(48)
C   5,%2
BNE KW_NEXT
L   5,3(50)
C   5,1
BNE KW_NEXT
L   5,3(4C)
C   5,7
BL  KW_BETTER
KW_NEXT:
A   3,3,%60
A   4,4,%1
C   4,%4
BL  KW_LOOP
C   2,%0
BL  KW_RET
O   5,0,%1
ST  5,2(48)
X   5,5,5
ST  5,2(50)
KW_RET:
J   15(0)
KW_BETTER:
O   7,5,%0
O   2,6,%0
B   KW_NEXT
#
##########################################################################
# 起動: カーネル変数を 0 にし, タスク表から TCB を作ってタスク 0 から始める
##########################################################################
KBOOT:
O   1,0,%440
WSR 2,1
O   2,0,%D80
KB_ZERO:
ST  0,2(0)
A   2,2,%4
C   2,%E80
BL  KB_ZERO
O   13,0,%C00
O   12,0,%F00
O   11,0,%0
SETHI 10,%0100
KB_TASK:
O   2,0,%0
KB_CLR:
A   3,13,2
ST  0,3(0)
A   2,2,%4
C   2,%40
BL  KB_CLR
ST  11,13(4)
ST  11,13(54)
L   1,12(0)
ST  1,13(40)
ST  10,13(44)
O   1,0,%1
ST  1,13(48)
L   1,12(4)
ST  1,13(4C)
ST  0,13(50)
A   13,13,%60
A   12,12,%8
A   11,11,%1
C   11,%4
BL  KB_TASK
O   11,0,%0
B   SCHED
#
##########################################################################
# ユーザタスク (ユーザモード, 開始時 GR1 = タスク番号, 他の GR = 0)
##########################################################################
# T0 (優先度 1): 出力タスク。GR9 = UART, GR2 = 次に出す文字の番地, GR3 = 文字, GR4 = ステータス
EQU 900
TASK0:
SETHI 9,%-1000
T0_LOOP:
X   1,1,1
SVC 5
O   2,1,%0
T0_CHAR:
L.b 3,2(0)
C   3,%0
BE  T0_LOOP
# 送信 FIFO が満杯 (ステータスのビット 3 が 1) なら待つ
T0_WAIT:
L   4,9(8)
N.c 4,4,%8
BNE T0_WAIT
ST  3,9(4)
A   2,2,%1
B   T0_CHAR
#
# T1 (優先度 2): スイッチのタスク。GR9 = GPIO, GR3 = スイッチ, GR4 = 待ちの残り回数
EQU 980
TASK1:
SETHI 9,%-FFF
T1_LOOP:
L   3,9(0)
N   3,3,%3
SL  3,3,%2
L   2,3(F20)
O   2,2,%0
X   1,1,1
SVC 4
L   4,DELAY
O   4,4,%0
T1_DELAY:
A   4,4,%-1
C   4,%0
BG  T1_DELAY
B   T1_LOOP
#
# T2, T3: 使わない
EQU A00
TASK_NONE:
SVC 0
#
##########################################################################
# 全タスク終了後 (カーネルモード): T0, T1 は終わらないので, ここには来ないはず
##########################################################################
EQU B00
APP_DONE:
B   DEAD
#
