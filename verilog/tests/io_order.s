# I/O 領域のテスト (AXI4 版 stm_axi_top 用, Verilog 版で追加)
#   テスト用スレーブ (tb/axi4_mem_slave.v) の I/O デバイス:
#     F0000000 (DEV_A) : 読むたびに「それまでに読まれた回数」を返す
#     F0000004 (DEV_B) : 書いた値のビット反転を返す
#   1. 予測ミス側の I/O ロードはバスに出ない (DEV_A の回数が増えない)
#   2. I/O へのストアは B サイクルの読み出しをしない (DEV_A の回数が増えない)
#   3. I/O へのストアの直後のロードは、ストアが終わってからデバイスを読む
#      (フォワーディングで読むと反転していない値になる)
#
# Header start
#
USING   14,300
USING_I 14,300
EQU 300
main:
X   0,0,0
O   14,0,%300
B   L1
#
EQU 3D0
DEAD:
DD000000
EQU 3F0
SUCCESS:
DF000000
#
# Header end
##########################################
EQU 400
L1:
O   1,0,%0
O   2,0,%5
B   L2
#
# 予測ミス側。ここが実行されたら (I/O が読まれたら) 失敗
SPEC:
L   3,10(0)
L   3,10(0)
B   DEAD
#
L2:
# アセンブラ (asm.pl / asm.py) は 1 パス目で SETHI を数えないので,
# SETHI はラベルより後に置く (前に置くとラベルの番地が 4 ずれる)。
SETHI 10,%-1000		# GR10 = F0000000 (%-1000 = F000) (I/O 領域)
# --- 1. CC をメモリオペランドの比較で作るので, BNE は E サイクルまで解決しない。
#        後方分岐なので taken と予測され, SPEC のロードが投機的に発行される。
#        実際は EQ なので not taken。
C   1,0(700)
BNE SPEC
C   1,0(700)
BNE SPEC
# --- DEV_A はまだ読まれていないので 0, 次は 1
L   3,10(0)
C   3,%0
BNE DEAD
L   3,10(0)
C   3,%1
BNE DEAD
# --- 2. DEV_A へのストアでは読み出しをしないので, 次の値は 2 のまま
ST  2,10(0)
L   3,10(0)
C   3,%2
BNE DEAD
# --- 3. DEV_B に 5 を書いてすぐ読む: ~5 = FFFFFFFA (+6 で 0)
ST  2,10(4)
L   3,10(4)
A   3,3,%6
C   3,%0
BNE DEAD
# 値を変えてもう一度 (ストア 2 回の後のロード)
ST  1,10(4)
ST  2,10(4)
L   3,10(4)
A   3,3,%6
C   3,%0
BNE DEAD
B   SUCCESS
#
EQU 700
D0:
00000000
